"""
情绪响应策略 — 每种情绪对应的 Agent 回复策略。

由 Supervisor 在路由时注入到子 Agent 的 System Prompt 中。
"""

EMOTION_STRATEGIES = {
    "frustrated": (
        "学员当前情绪：沮丧。"
        "应对策略：先安抚学员情绪，降低当前内容的难度，"
        "给出具体提示或换个角度解释。不要继续施加压力。"
    ),
    "bored": (
        "学员当前情绪：无聊。"
        "应对策略：换一种更有趣的讲法，可以加入互动、小测验或挑战。"
        "避免重复性的内容和说教。"
    ),
    "anxious": (
        "学员当前情绪：焦虑。"
        "应对策略：先安抚学员的焦虑感，给一个简单的小任务帮 ta 重建信心。"
        "不要强调任务量和难度，强调'慢慢来、你能行'。"
    ),
    "confident": (
        "学员当前情绪：自信。"
        "应对策略：适当加大难度，给更多挑战。"
        "可以利用学员的自信状态推进更深的内容。"
    ),
    "disengaged": (
        "学员当前情绪：懈怠。"
        "应对策略：给一个低门槛、容易完成的小目标。"
        "提醒学员之前的进步和成就感，帮助 ta 找回学习动力。"
    ),
    "accomplished": (
        "学员当前情绪：成就感。"
        "应对策略：先肯定学员的努力和成果，然后推荐类似难度的挑战。"
        "不要扫兴，保持正向强化。"
    ),
    "neutral": (
        "学员当前情绪：中性。"
        "应对策略：正常教学节奏，不需要特别调整。"
    ),
}


def get_emotion_strategy(emotion: str) -> str:
    """根据情绪状态返回对应的响应策略"""
    return EMOTION_STRATEGIES.get(emotion, EMOTION_STRATEGIES["neutral"])
